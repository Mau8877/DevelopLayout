-- =====================================================================
-- Schema `authentication`: identidad, acceso y trazabilidad.
-- UT-HUI-BASE-BE-01. Reglas: SCHEMAS_BD_BACKEND.md, PERSISTENCIA_BD_BACKEND.md
-- y BASE_DE_DATOS_PRIVADA_RLS.md. Todo va calificado (`authentication.`),
-- nada depende del search_path y nada queda en `public`.
--
-- Contexto de RLS (lo fija el service con set_config(..., true)):
--   app.current_user  UUID del usuario autenticado
--   app.login_email   correo del login/recuperación en curso (una sola fila)
--   app.refresh_hash  hash del refresh token que presenta el cliente
--   app.is_admin      'true' solo para SUPER_ADMIN
-- Un GUC personalizado queda como '' (no NULL) tras la primera transacción
-- que lo usa en la conexión; por eso toda comparación pasa por nullif(..., '')
-- y nunca castea '' a uuid.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS authentication;

-- ---------------------------------------------------------------------
-- usuario
-- ---------------------------------------------------------------------
CREATE TABLE authentication.usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_usuario UUID         NOT NULL UNIQUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ,
    email          VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    estado         VARCHAR(20)  NOT NULL CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    -- Permite la FK compuesta de sesion (usuario_id, usuario_codigo).
    CONSTRAINT uq_usuario_id_codigo UNIQUE (id, codigo_usuario)
);

CREATE UNIQUE INDEX uq_usuario_email
    ON authentication.usuario (lower(email))
    WHERE deleted_at IS NULL;

ALTER TABLE authentication.usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE authentication.usuario FORCE ROW LEVEL SECURITY;

CREATE POLICY usuario_aislamiento ON authentication.usuario
    USING (
        codigo_usuario = nullif(current_setting('app.current_user', true), '')::uuid
        OR lower(email) = lower(nullif(current_setting('app.login_email', true), ''))
    )
    WITH CHECK (
        codigo_usuario = nullif(current_setting('app.current_user', true), '')::uuid
        OR lower(email) = lower(nullif(current_setting('app.login_email', true), ''))
    );

-- ---------------------------------------------------------------------
-- rol (catálogo)
-- ---------------------------------------------------------------------
-- RLS-OPT-OUT: catálogo de roles, sin datos sensibles
CREATE TABLE authentication.rol (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_rol  UUID         NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ,
    nombre      VARCHAR(50)  NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    is_active   BOOLEAN      NOT NULL DEFAULT true
);

INSERT INTO authentication.rol (codigo_rol, nombre, descripcion)
VALUES (gen_random_uuid(), 'SUPER_ADMIN', 'Control total del sistema'),
       (gen_random_uuid(), 'USUARIO', 'Usuario estándar');

-- ---------------------------------------------------------------------
-- usuario_rol
-- ---------------------------------------------------------------------
CREATE TABLE authentication.usuario_rol (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_usuario_rol UUID        NOT NULL UNIQUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at         TIMESTAMPTZ,
    usuario_id         BIGINT      NOT NULL REFERENCES authentication.usuario (id),
    rol_id             BIGINT      NOT NULL REFERENCES authentication.rol (id),
    is_active          BOOLEAN     NOT NULL DEFAULT true
);

CREATE INDEX ix_usuario_rol_usuario_id ON authentication.usuario_rol (usuario_id);
CREATE INDEX ix_usuario_rol_rol_id ON authentication.usuario_rol (rol_id);
CREATE UNIQUE INDEX uq_usuario_rol_asignacion
    ON authentication.usuario_rol (usuario_id, rol_id)
    WHERE deleted_at IS NULL;

ALTER TABLE authentication.usuario_rol ENABLE ROW LEVEL SECURITY;
ALTER TABLE authentication.usuario_rol FORCE ROW LEVEL SECURITY;

CREATE POLICY usuario_rol_aislamiento ON authentication.usuario_rol
    USING (usuario_id IN (
        SELECT u.id FROM authentication.usuario u
        WHERE u.codigo_usuario = nullif(current_setting('app.current_user', true), '')::uuid
    ))
    WITH CHECK (usuario_id IN (
        SELECT u.id FROM authentication.usuario u
        WHERE u.codigo_usuario = nullif(current_setting('app.current_user', true), '')::uuid
    ));

-- ---------------------------------------------------------------------
-- sesion
-- ---------------------------------------------------------------------
-- El refresh token nunca se guarda en claro: solo su SHA-256 en hexadecimal
-- (64 caracteres). VARCHAR y no CHAR para que Hibernate valide el tipo.
CREATE TABLE authentication.sesion (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_sesion         UUID         NOT NULL UNIQUE,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at            TIMESTAMPTZ,
    usuario_id            BIGINT       NOT NULL,
    usuario_codigo        UUID         NOT NULL,
    refresh_hash          VARCHAR(64)  NOT NULL UNIQUE CHECK (refresh_hash ~ '^[0-9a-f]{64}$'),
    refresh_hash_anterior VARCHAR(64)  CHECK (refresh_hash_anterior ~ '^[0-9a-f]{64}$'),
    estado                VARCHAR(20)  NOT NULL CHECK (estado IN ('ACTIVA', 'REVOCADA', 'EXPIRADA')),
    tipo_cliente          VARCHAR(10)  NOT NULL CHECK (tipo_cliente IN ('WEB', 'MOBILE')),
    ip                    VARCHAR(45),
    user_agent            VARCHAR(255),
    expira_en             TIMESTAMPTZ  NOT NULL,
    ultimo_uso_en         TIMESTAMPTZ,
    revocada_en           TIMESTAMPTZ,
    motivo_revocacion     VARCHAR(30)
        CHECK (motivo_revocacion IN ('LOGOUT', 'USUARIO', 'ADMIN', 'REUSO', 'RESET_PASSWORD')),
    -- usuario_codigo existe para que RLS compare sin subconsulta; la FK
    -- compuesta garantiza que coincida con el usuario_id.
    CONSTRAINT fk_sesion_usuario FOREIGN KEY (usuario_id, usuario_codigo)
        REFERENCES authentication.usuario (id, codigo_usuario)
);

CREATE INDEX ix_sesion_usuario_id ON authentication.sesion (usuario_id);
CREATE INDEX ix_sesion_usuario_codigo ON authentication.sesion (usuario_codigo);
CREATE INDEX ix_sesion_refresh_hash_anterior ON authentication.sesion (refresh_hash_anterior);

ALTER TABLE authentication.sesion ENABLE ROW LEVEL SECURITY;
ALTER TABLE authentication.sesion FORCE ROW LEVEL SECURITY;

CREATE POLICY sesion_aislamiento ON authentication.sesion
    USING (
        usuario_codigo = nullif(current_setting('app.current_user', true), '')::uuid
        OR current_setting('app.is_admin', true) = 'true'
        OR refresh_hash = nullif(current_setting('app.refresh_hash', true), '')
        OR refresh_hash_anterior = nullif(current_setting('app.refresh_hash', true), '')
    )
    WITH CHECK (
        usuario_codigo = nullif(current_setting('app.current_user', true), '')::uuid
        OR current_setting('app.is_admin', true) = 'true'
    );

-- ---------------------------------------------------------------------
-- bitacora (solo inserción desde la app)
-- ---------------------------------------------------------------------
CREATE TABLE authentication.bitacora (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_bitacora  UUID         NOT NULL UNIQUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at       TIMESTAMPTZ,
    usuario_codigo   UUID,
    accion           VARCHAR(100) NOT NULL,
    modulo           VARCHAR(50)  NOT NULL,
    entidad          VARCHAR(100),
    entidad_codigo   UUID,
    resultado        VARCHAR(10)  NOT NULL CHECK (resultado IN ('EXITO', 'FALLO')),
    ip               VARCHAR(45),
    user_agent       VARCHAR(255),
    detalle          JSONB
);

CREATE INDEX ix_bitacora_created_at ON authentication.bitacora (created_at);
CREATE INDEX ix_bitacora_accion ON authentication.bitacora (accion);
CREATE INDEX ix_bitacora_usuario_codigo ON authentication.bitacora (usuario_codigo);

ALTER TABLE authentication.bitacora ENABLE ROW LEVEL SECURITY;
ALTER TABLE authentication.bitacora FORCE ROW LEVEL SECURITY;

-- Excepción documentada (docs/seguridad/RLS_EXCEPCIONES.md): el evento puede
-- ocurrir sin usuario (p. ej. un login fallido) y la tabla es de solo inserción.
CREATE POLICY bitacora_insercion ON authentication.bitacora
    FOR INSERT
    WITH CHECK (true);

CREATE POLICY bitacora_lectura ON authentication.bitacora
    FOR SELECT
    USING (current_setting('app.is_admin', true) = 'true');

-- Solo la función de purga (SECURITY DEFINER) activa este contexto. app_runtime
-- no tiene el privilegio DELETE, así que esta política no le abre nada.
CREATE POLICY bitacora_purga ON authentication.bitacora
    FOR DELETE
    USING (current_setting('app.purga', true) = 'on');

CREATE FUNCTION authentication.purgar_bitacora(meses integer)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, authentication
AS $$
DECLARE
    borradas bigint;
BEGIN
    IF meses IS NULL OR meses < 1 THEN
        RAISE EXCEPTION 'meses debe ser un entero >= 1';
    END IF;
    PERFORM set_config('app.purga', 'on', true);
    DELETE FROM authentication.bitacora
    WHERE created_at < now() - make_interval(months => meses);
    GET DIAGNOSTICS borradas = ROW_COUNT;
    RETURN borradas;
END;
$$;

REVOKE ALL ON FUNCTION authentication.purgar_bitacora(integer) FROM PUBLIC;
